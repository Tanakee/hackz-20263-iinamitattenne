# 階層を辿ってスコアを推定する
# 距離1ごとにスコアを5%割り引く（親に近いほど少し低くなる）
HYPERNYM_DECAY = 0.95
MAX_HYPERNYM_DEPTH = 10


def lookup_scale_with_hypernyms(word, lemma=None):
    """辞書 → 階層探索の順でスケールを返す。見つからなければ None"""
    # まず直接辞書を引く
    if word in SCALE_DICT:
        return SCALE_DICT[word]
    if lemma and lemma in SCALE_DICT:
        return SCALE_DICT[lemma]

    # 階層を辿る
    current = word
    depth = 0
    while depth < MAX_HYPERNYM_DEPTH:
        parent = HYPERNYM_TREE.get(current)
        if parent is None:
            # lemmaでも試す
            if lemma and depth == 0:
                parent = HYPERNYM_TREE.get(lemma)
            if parent is None:
                break
        depth += 1
        current = parent
        if current in SCALE_DICT:
            return round(SCALE_DICT[current] * (HYPERNYM_DECAY ** depth))

    return None
